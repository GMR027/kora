const dictionaries: Record<Locale, Record<MessageKey, string>> = { es, en };

export const locale = writable<Locale>("es");

export function setLocale(next: Locale) {
  locale.set(next);
  if (typeof document !== "undefined") {
    document.documentElement.lang = next;
  }
}

export function translate(
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const dictionary = dictionaries[get(locale)] ?? es;
  let message = dictionary[key] ?? es[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }
  }
  return message;
}

export const t = derived(locale, ($locale) => {
  const dictionary = dictionaries[$locale] ?? es;
  return (key: MessageKey, params?: Record<string, string | number>) => {
    let message = dictionary[key] ?? es[key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        message = message.replaceAll(`{${name}}`, String(value));
      }
    }
    return message;
  };
});

export function formatDate(
  value: string | Date,
  options: Intl.DateTimeFormatOptions = {
    day: "numeric",
    month: "short",
    year: "numeric",
  },
) {
  return new Intl.DateTimeFormat(get(locale), options).format(
    typeof value === "string" ? new Date(value) : value,
  );
}

export function formatBytes(bytes: number) {
  const units = ["B", "KB", "MB", "GB"];
  let value = bytes;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return `${new Intl.NumberFormat(get(locale), {
    maximumFractionDigits: unit === 0 ? 0 : 1,
  }).format(value)} ${units[unit]}`;
}

export function formatDuration(milliseconds: number) {
  const totalSeconds = Math.max(0, Math.round(milliseconds / 1000));
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;
  return hours > 0
    ? `${hours}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`
    : `${minutes}:${String(seconds).padStart(2, "0")}`;
}

export function errorKey(code: string | undefined): MessageKey {
  switch (code) {
    case "unsupported":
    case "not_implemented":
      return "error.unsupported";
    case "not_found":
      return "error.notFound";
    case "invalid_input":
    case "conflict":
      return "error.invalid";
    case "cancelled":
      return "error.cancelled";
    case "io":
    case "storage":
    case "database":
      return "error.network";
    default:
      return "error.generic";
  }
}
